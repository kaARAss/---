function updatePage(filename, contentBody) {
    let html = fs.readFileSync(filename, 'utf8');
    // Extract header and footer
    const headerMatch = html.match(/(.*?<\/header>)/s);
    const footerMatch = html.match(/(<footer[\s\S]*)/s);
    if (!headerMatch || !footerMatch) return;
    
    const newHtml = `
${headerMatch[1]}
${baseStyle}
<div class="legal-content">
${contentBody}
</div>
${footerMatch[1]}
`;
    fs.writeFileSync(filename, newHtml);
}

